// איות בעברית בדיבור ("כף הא נון" / "כ ה ן") -> מילה. משמש לשם משפחה שלא זוהה בהקלטה רגילה.
const NAMES = {
  'אלף': 'א', 'בית': 'ב', 'בט': 'ב', 'גימל': 'ג', 'גימיל': 'ג', 'דלת': 'ד', 'הא': 'ה', 'הי': 'ה', 'וו': 'ו', 'ואו': 'ו', 'זין': 'ז', 'חית': 'ח', 'חט': 'ח', 'טית': 'ט', 'טט': 'ט',
  'יוד': 'י', 'יוּד': 'י', 'כף': 'כ', 'כאף': 'כ', 'ךף': 'ך', 'למד': 'ל', 'לָמֶד': 'ל', 'מם': 'מ', 'מֶם': 'מ', 'נון': 'נ', 'סמך': 'ס', 'עין': 'ע', 'פא': 'פ', 'פה': 'פ', 'צדי': 'צ', 'צדיק': 'צ', 'צאדי': 'צ',
  'קוף': 'ק', 'ריש': 'ר', 'שין': 'ש', 'סין': 'ש', 'תו': 'ת', 'תיו': 'ת',
};
const FINAL = { 'כ': 'ך', 'מ': 'ם', 'נ': 'ן', 'פ': 'ף', 'צ': 'ץ' };
const SING = 'אבגדהוזחטיכלמנסעפצקרשת';

/** מחזיר את המילה שאוית, או '' אם לא זוהו לפחות 2 אותיות. שמות אותיות סופיות ("נון סופית") נתמכים. */
export function spokenLetters(t) {
  const toks = String(t || '').replace(/[.,!?'"׳״-]/g, ' ').split(/\s+/).filter(Boolean);
  const out = [];
  for (let i = 0; i < toks.length; i++) {
    const tk = toks[i];
    if (tk === 'סופית' || tk === 'סופי') { const l = out.pop(); if (l) out.push(FINAL[l] || l); continue; }
    if (tk.length === 1 && /[א-ת]/.test(tk)) out.push(tk);
    else if (NAMES[tk]) out.push(NAMES[tk]);
    else if (/^[א-ת]+$/.test(tk) && tk.length <= 3 && [...tk].every((c) => SING.includes(c) || 'ךםןףץ'.includes(c)) && toks.length > 2) out.push(...tk);     // אותיות מודבקות ("כהן" לא; "כ ה" כן)
    else return '';
  }
  if (out.length < 2) return '';
  return out.map((c, i) => (i === out.length - 1 && FINAL[c] ? FINAL[c] : c)).join('');
}
