// סימון אות סופית: בעברית אחרי האות ("נון סופית"), ביידיש לפניה ("לאנגער נון" = נון ארוכה, "שלוס מעם" = מם סגורה)
const FINAL_MARK = new Set(['סופית', 'סופי', 'לאנגער', 'לאנגע', 'לאנג', 'לאנגר', 'שלוס', 'שלוש', 'שליסעל', 'שליסל', 'שלוסל', 'שליסעלע', 'שליסלע', 'לאנגע', 'לאנגער', 'לאנגן', 'אנדע', 'אנדיגע', 'סוף']);
const FINAL = { 'כ': 'ך', 'מ': 'ם', 'נ': 'ן', 'פ': 'ף', 'צ': 'ץ' };
const SING = 'אבגדהוזחטיכלמנסעפצקרשת';

/** מחזיר את המילה שאוית, או '' אם לא זוהו לפחות 2 אותיות. שמות אותיות סופיות ("נון סופית") נתמכים. */
export function spokenLetters(t) {
  const toks = String(t || '').replace(/[.,!?'"׳״-]/g, ' ').split(/\s+/).filter(Boolean);
  const out = [];
  let pendingFinal = false;
  for (let i = 0; i < toks.length; i++) {
    const tk = toks[i].replace(/[\u0591-\u05c7]/g, '');
    if (FINAL_MARK.has(tk)) {
      if (out.length && !pendingFinal && !(toks[i + 1] && (NAMES[toks[i + 1]] || (toks[i + 1].length === 1 && /[א-ת]/.test(toks[i + 1]))))) { const l = out.pop(); out.push(FINAL[l] || l); }   // אחרי האות
      else pendingFinal = true;                                                                                                                  // לפני האות (יידיש)
      continue;
    }
    let letter = '';
    if (tk.length === 1 && /[א-ת]/.test(tk)) letter = tk;
    else if (NAMES[tk]) letter = NAMES[tk];
    else if (/^[א-ת]+$/.test(tk) && tk.length <= 3 && [...tk].every((c) => SING.includes(c) || 'ךםןףץ'.includes(c)) && toks.length > 2) { out.push(...tk); continue; }     // אותיות מודבקות ("כ ה" כן; "כהן" לא)
    else return '';
    if (pendingFinal) { letter = FINAL[letter] || letter; pendingFinal = false; }
    out.push(letter);
  }
  if (out.length < 2) return '';
  return out.map((c, i) => (i === out.length - 1 && FINAL[c] ? FINAL[c] : c)).join('');
}
